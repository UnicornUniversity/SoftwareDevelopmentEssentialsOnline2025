// BINARY
// affects on two arguments

const x = 1 + 2; // "+" is binary operator
console.log(x);

// UNARY
// affects on one argument
const y = -x;
console.log(y);

let z = false;
z = !z; // ! <- unary operator ("not")
console.log(z);

// TERNARY
const b = "test";
// this is also condition
console.log(b === "hello" ? "mom" : "dad");

